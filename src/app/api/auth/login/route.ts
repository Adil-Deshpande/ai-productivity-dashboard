import { apiHandler } from '@/lib/apiHandler';
import { authController } from '@/modules/auth/controller';

/**
 * @swagger
 * /api/auth/login:
 *   post:
 *     summary: Login user
 *     tags: [Auth]
 *     requestBody:
 *       required: true
 *       content:
 *         application/json:
 *           schema:
 *             type: object
 *             required: [email, password]
 *             properties:
 *               email:
 *                 type: string
 *               password:
 *                 type: string
 *     responses:
 *       200:
 *         description: Login successful (sets HTTP-only cookie)
 */
export const POST = apiHandler((req: Request) => authController.login(req));
